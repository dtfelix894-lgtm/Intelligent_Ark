CREATE TABLE IF NOT EXISTS users (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account         TEXT        NOT NULL UNIQUE,
    password_hash   TEXT        NOT NULL,
    role            TEXT        NOT NULL DEFAULT 'student'
                        CHECK (role IN ('student', 'admin')),
    is_demo         BOOLEAN     NOT NULL DEFAULT FALSE,
    created_at      TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS user_profiles (
    user_id             BIGINT PRIMARY KEY REFERENCES users(id),
    school              TEXT,
    student_id          TEXT,
    education           TEXT,
    qq_email            TEXT,
    admin_type          TEXT CHECK (admin_type IS NULL OR admin_type IN ('G', 'C')),
    school_name         TEXT,
    companion_persona   TEXT
);

CREATE TABLE IF NOT EXISTS chat_messages (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id     BIGINT      NOT NULL REFERENCES users(id),
    scenario    TEXT        NOT NULL,
    role        TEXT        NOT NULL CHECK (role IN ('user', 'assistant')),
    content     TEXT        NOT NULL,
    created_at  TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_chat_messages_user ON chat_messages (user_id, created_at);

CREATE TABLE IF NOT EXISTS risk_events (
    id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id               BIGINT      NOT NULL REFERENCES users(id),
    scenario              TEXT        NOT NULL,
    level                 TEXT        NOT NULL CHECK (level IN ('green', 'yellow', 'red')),
    score                 INTEGER     NOT NULL,
    tags                  JSONB       NOT NULL DEFAULT '[]'::jsonb,
    summary               TEXT        NOT NULL,
    handled               BOOLEAN     NOT NULL DEFAULT FALSE,
    created_at            TIMESTAMPTZ NOT NULL DEFAULT now(),
    handled_at            TIMESTAMPTZ,
    handled_by            TEXT,
    action                TEXT,
    note                  TEXT,
    assignee              TEXT,
    claimed_at            TIMESTAMPTZ,
    status                TEXT        CHECK (status IS NULL OR status IN (
        'pending', 'claimed', 'verifying', 'intervening', 'referred', 'monitoring', 'closed', ''
    )),
    closed_at             TIMESTAMPTZ,
    closure_label         TEXT,
    closure_other_person  BOOLEAN     NOT NULL DEFAULT FALSE,
    closure_note          TEXT,
    claim_due_at          TIMESTAMPTZ,
    escalated_at          TIMESTAMPTZ
);

CREATE INDEX IF NOT EXISTS idx_risk_events_level ON risk_events (level, created_at);
CREATE INDEX IF NOT EXISTS idx_risk_events_status ON risk_events (status, created_at);
CREATE INDEX IF NOT EXISTS idx_risk_events_assignee ON risk_events (assignee) WHERE assignee IS NOT NULL;
CREATE INDEX IF NOT EXISTS idx_risk_events_user ON risk_events (user_id, created_at);

CREATE TABLE IF NOT EXISTS event_transitions (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_id     BIGINT      NOT NULL REFERENCES risk_events(id),
    from_status  TEXT        NOT NULL,
    to_status    TEXT        NOT NULL,
    actor        TEXT        NOT NULL,
    reason       TEXT,
    created_at   TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_event_transitions_event ON event_transitions (event_id, created_at);

CREATE TABLE IF NOT EXISTS follow_up_records (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_id         BIGINT      NOT NULL REFERENCES risk_events(id),
    type             TEXT        NOT NULL,
    occurred_at      TIMESTAMPTZ NOT NULL,
    summary          TEXT        NOT NULL,
    referral_target  TEXT,
    actor            TEXT        NOT NULL,
    created_at       TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_follow_up_event ON follow_up_records (event_id, created_at);

CREATE TABLE IF NOT EXISTS reassessments (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_id      BIGINT      NOT NULL REFERENCES risk_events(id),
    due_date      DATE        NOT NULL,
    completed_at  TIMESTAMPTZ,
    result        TEXT,
    actor         TEXT,
    created_at    TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_reassessments_event ON reassessments (event_id, due_date);

CREATE TABLE IF NOT EXISTS audit_logs (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    actor        TEXT        NOT NULL,
    action       TEXT        NOT NULL,
    target_type  TEXT        NOT NULL,
    target_id    TEXT        NOT NULL,
    meta         JSONB,
    created_at   TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_audit_logs_created ON audit_logs (created_at DESC);
CREATE INDEX IF NOT EXISTS idx_audit_logs_target ON audit_logs (target_type, target_id);
